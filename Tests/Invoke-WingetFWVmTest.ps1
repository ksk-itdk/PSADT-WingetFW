#Requires -Version 5.1

<#
.SYNOPSIS
    Runs the WingetFW test suite on the sandbox VM and writes TEST-RESULTS.md.

.DESCRIPTION
    1. Copies the WingetFW package (Toolkit\<Package>) and Invoke-WingetFWTestSuite.ps1 to the VM over SSH (key login).
    2. Runs the suite on the VM (Admin tests as SYSTEM via PsExec, User tests as the SSH user).
    3. Copies WingetFW-TestResults.log/.json back to Tests\results.
    4. Generates Tests\TEST-RESULTS.md from the JSON.

    Use -ReportOnly to only regenerate TEST-RESULTS.md from an existing results JSON.

.PARAMETER ComputerName
    Sandbox VM (SSH).

.PARAMETER UserName
    SSH user on the VM (must be a local administrator).

.PARAMETER KeyFile
    Private key for SSH key login (no passphrase).

.PARAMETER RemoteRoot
    Folder on the VM used for the test run (outside user profiles, SYSTEM must read it).

.PARAMETER Package
    Package folder in Toolkit to test. Default WinGetFW.

.PARAMETER ReportOnly
    Skip the VM run, only rebuild TEST-RESULTS.md from Tests\results\WingetFW-TestResults.json.

.EXAMPLE
    .\Invoke-WingetFWVmTest.ps1

.EXAMPLE
    .\Invoke-WingetFWVmTest.ps1 -ReportOnly

.NOTES
    Maintained by: KSKITDK
    Version      : 1.2.1

    Release notes
    1.2.1  - Default -Package is WinGetFW (no version in the folder name). Default -ComputerName is 192.168.58.136.
    1.2.0  - -Package selects the package folder to test; default WinGetFW5.0.0 (Invoke-AppDeployToolkit.exe).
           - The report shows the package exe and PSADT version.
    1.1.1  - Maintainer set to KSKITDK, GitHub link added.
    1.1.0  - Report lists Postman.Postman as test package.
    1.0.0  - First version.

.LINK
    https://github.com/ksk-itdk/PSADT-WingetFW
#>
[CmdletBinding()]
Param (
    [Parameter()]
    [String]$ComputerName = '192.168.58.136',

    [Parameter()]
    [String]$UserName = 'TEST',

    [Parameter()]
    [String]$KeyFile = "$HOME\.ssh\wingetfw_sandbox",

    [Parameter()]
    [String]$RemoteRoot = 'C:\temp\wingetfw-vmtest',

    [Parameter()]
    [String]$Package = 'WinGetFW',

    [Parameter()]
    [Switch]$ReportOnly
)

$ErrorActionPreference = 'Stop'
$testsDir   = $PSScriptRoot
$packageDir = Join-Path (Split-Path $testsDir -Parent) "Toolkit\$Package"
$resultsDir = Join-Path $testsDir 'results'
$jsonFile   = Join-Path $resultsDir 'WingetFW-TestResults.json'
$reportFile = Join-Path $testsDir 'TEST-RESULTS.md'
$target     = "$UserName@$ComputerName"
$remoteFwd  = $RemoteRoot -replace '\\', '/'
$sshOpts    = @('-i', $KeyFile, '-o', 'IdentitiesOnly=yes', '-o', 'BatchMode=yes', '-o', 'ServerAliveInterval=30')

If (-not $ReportOnly) {
    New-Item -ItemType Directory -Path $resultsDir -Force | Out-Null
    Write-Host "Copying package and suite to $target`:$RemoteRoot"
    & ssh @sshOpts $target "if exist `"$RemoteRoot\$Package`" rmdir /s /q `"$RemoteRoot\$Package`" & if not exist `"$RemoteRoot`" mkdir `"$RemoteRoot`""
    & scp @sshOpts -q -r $packageDir (Join-Path $testsDir 'Invoke-WingetFWTestSuite.ps1') "$($target):$remoteFwd/"
    If ($LASTEXITCODE -ne 0) { Throw "scp failed ($LASTEXITCODE)" }

    Write-Host 'Running test suite on the VM (takes several minutes, do not interrupt)'
    & ssh @sshOpts $target "powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$RemoteRoot\Invoke-WingetFWTestSuite.ps1`" -Root `"$RemoteRoot`" -PackageFolder `"$Package`"" 2>&1 |
        Where-Object { $_ -notmatch 'CLIXML|<Objs|</Objs>' } | Tee-Object -FilePath (Join-Path $resultsDir 'console.txt')
    & scp @sshOpts -q "$($target):$remoteFwd/results/WingetFW-TestResults.log" "$($target):$remoteFwd/results/WingetFW-TestResults.json" "$resultsDir/"
    If ($LASTEXITCODE -ne 0) { Throw "Could not copy results back ($LASTEXITCODE)" }
}

# ---------------------------------------------------------------- TEST-RESULTS.md
$run = Get-Content $jsonFile -Raw -Encoding UTF8 | ConvertFrom-Json
$tests = @($run.Tests)
$passCount = @($tests | Where-Object Result -eq 'PASS').Count
Function ConvertTo-MdCell([String]$Text) { ($Text -replace '\|', '\|' -replace '\r?\n', ' ').Trim() }

$md = New-Object System.Collections.Generic.List[String]
$md.Add('# WingetFW test results')
$md.Add('')
$md.Add('> Generated by `Tests/Invoke-WingetFWVmTest.ps1` from `Tests/results/WingetFW-TestResults.json`. Do not edit by hand, run the script again.')
$md.Add('')
$md.Add("**Result: $passCount of $($tests.Count) tests passed.**")
$md.Add('')
$md.Add('| Item | Value |')
$md.Add('|---|---|')
$md.Add("| Run date | $($run.RunDate) |")
$md.Add("| Machine | $($run.Computer) ($($run.Os)) |")
$packageText = If ($run.PSObject.Properties['PackageExe']) { "PSADT $($run.PsadtVersion), ``$($run.PackageExe)``" } Else { 'PSADT v3, `Deploy-Application.exe`' }
$md.Add("| WingetFW package | $($run.PackageVersion) ($packageText) |")
$md.Add("| winget | $($run.WingetVersion) ``$($run.WingetPath)`` |")
$md.Add("| Admin-mode tests | run as SYSTEM via ``$($run.PsExec) -s`` |")
$md.Add("| User-mode tests | run as ``$($run.RunnerUser)`` without PsExec |")
$md.Add("| Test packages | ``7zip.7zip`` (older: $($run.SevenZipOlder), latest: $($run.SevenZipLatest)), ``jqlang.jq`` (portable), ``Postman.Postman`` (user scope EXE) |")
$enabledSettings = If ($run.AdminSettingsEnabled) { (@($run.AdminSettingsEnabled) | ForEach-Object { '`{0}`' -f $_ }) -join ', ' } Else { 'none (already enabled)' }
$md.Add("| winget admin settings enabled during run | $enabledSettings - restored afterwards |")
$md.Add('')
$md.Add('## Summary')
$md.Add('')
$md.Add('| ID | Result | Action | Run as | Exit code | Test | Parameters |')
$md.Add('|---|---|---|---|---|---|---|')
ForEach ($t in $tests) {
    $icon = If ($t.Result -eq 'PASS') { 'PASS' } Else { '**FAIL**' }
    $paramList = (@($t.Parameters) | ForEach-Object { '`-{0}`' -f $_ }) -join ' '
    $md.Add("| [$($t.Id)](#$($t.Id.ToLower())) | $icon | $($t.Action) | $($t.RunAs) | $($t.ExitText) | $(ConvertTo-MdCell $t.Title) | $paramList |")
}
$md.Add('')
$md.Add('## Parameter coverage')
$md.Add('')
$md.Add('Each WingetFW parameter and the tests that used it.')
$md.Add('')
$md.Add('| Parameter | Tests |')
$md.Add('|---|---|')
$tests | ForEach-Object { $t = $_; @($t.Parameters) | ForEach-Object { [PSCustomObject]@{ P = $_; Id = $t.Id } } } | Group-Object P | Sort-Object Name |
    ForEach-Object { $md.Add("| ``-$($_.Name)`` | $(($_.Group.Id | Select-Object -Unique) -join ', ') |") }
$md.Add('')
$md.Add('## Details')
ForEach ($t in $tests) {
    $md.Add('')
    $md.Add("### $($t.Id)")
    $md.Add('')
    $md.Add("**$($t.Title)** - $($t.Result)")
    $md.Add('')
    $md.Add("- Run as: $($t.RunAs)")
    $md.Add("- Exit code: $($t.ExitText) ($($t.DurationSec) s)")
    $md.Add("- Toolkit log: ``$($t.ToolkitLog)``")
    $md.Add('')
    $md.Add('Command:')
    $md.Add('')
    $md.Add('```')
    $md.Add($t.Command)
    $md.Add('```')
    $md.Add('')
    If (@($t.WingetCalls).Count) {
        $md.Add('winget command line(s) from the toolkit log:')
        $md.Add('')
        $md.Add('```')
        @($t.WingetCalls) | ForEach-Object { $md.Add("winget $_") }
        $md.Add('```')
    }
    Else { $md.Add('winget was not started.') }
    $md.Add('')
    $md.Add('| Check | Result |')
    $md.Add('|---|---|')
    @($t.Checks) | ForEach-Object { $md.Add("| $(ConvertTo-MdCell $_.Text) | $(If ($_.Ok) { 'OK' } Else { '**FAIL**' }) |") }
    $md.Add('')
    $md.Add('<details><summary>Toolkit log excerpt</summary>')
    $md.Add('')
    $md.Add('```')
    @($t.LogExcerpt) | ForEach-Object { $md.Add($_) }
    $md.Add('```')
    $md.Add('')
    $md.Add('</details>')
}
$md | Set-Content -Path $reportFile -Encoding UTF8
Write-Host "Report: $reportFile ($passCount/$($tests.Count) passed)"
